let currentLang='en', currentTheme='dark';

function setLang(lang){
  currentLang=lang;
  document.querySelectorAll('.lang-btn').forEach(b=>b.classList.toggle('active',b.textContent.toLowerCase()===lang));
  document.querySelectorAll('[data-i]').forEach(el=>{
    const k=el.getAttribute('data-i');
    if(T[lang][k]!==undefined) el.innerHTML=T[lang][k];
  });
  document.documentElement.lang=lang;
}

function toggleTheme(){
  currentTheme = currentTheme==='dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', currentTheme);
  document.getElementById('themeBtn').textContent = currentTheme==='dark' ? '🌙' : '☀️';
}

function toggle(header){
  const body=header.nextElementSibling, chev=header.querySelector('.exp-chevron');
  const isOpen=body.classList.contains('open');
  document.querySelectorAll('.exp-body').forEach(b=>b.classList.remove('open'));
  document.querySelectorAll('.exp-chevron').forEach(c=>c.classList.remove('open'));
  if(!isOpen){body.classList.add('open');chev.classList.add('open');}
}

